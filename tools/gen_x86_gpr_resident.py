#!/usr/bin/env python3
"""GPR experiment: keep two D-row words resident across each round.

Same SSE2/System V contract and arithmetic as gen_x86_gpr_chunk_root.py.
At each round boundary D0/D1 live in eax/esi; D2/D3 park in xmm0/xmm1.
Execute columns 0,1 then 2,3; diagonals 3,0 then 1,2. Gs within each
half-round are independent, so this ordering avoids unnecessary transfers:

  boundary / columns 0,1: eax=D0 esi=D1 xmm0=D2 xmm1=D3
  columns 2,3 / diagonals 3,0: eax=D2 esi=D3 xmm2=D0 xmm3=D1
  diagonals 1,2 / next boundary: eax=D0 esi=D1 xmm0=D2 xmm1=D3

Eight GP/XMM moves per round instead of sixteen. No packed ADD/ROT,
additional branch, spill, ISA requirement or output-format change.
"""
import gen_x86_gpr_chunk_root as scalar


def pair(quads, words):
    left = scalar.g(quads[0], 'eax', words[0], words[1])
    right = scalar.g(quads[1], 'esi', words[2], words[3])
    return [ins for stage in zip(left, right) for ins in stage]


def kernel():
    old = scalar.kernel()
    start = next(i for i, line in enumerate(old) if line.startswith('// Round 0'))
    feed = old.index('xor r8d, ebx')
    setup = old[:start]
    # Length and flags become parked D2/D3; D0/D1 start at zero in GPRs.
    setup = [line.replace('movd xmm2, eax', 'movd xmm0, eax')
                 .replace('movd xmm3, eax', 'movd xmm1, eax')
                 .replace('pxor xmm0, xmm0', 'xor eax, eax')
                 .replace('pxor xmm1, xmm1', 'xor esi, esi') for line in setup]
    schedule = list(range(16))
    body = []
    for rnd in range(7):
        body += [f'// Round {rnd}; D0/D1 resident; message indices {schedule}']
        body += pair(scalar.COLUMNS[:2], schedule[:4])
        body += ['movd xmm2, eax', 'movd xmm3, esi', 'movd eax, xmm0', 'movd esi, xmm1']
        body += pair(scalar.COLUMNS[2:], schedule[4:8])
        body += pair([scalar.DIAGONALS[3], scalar.DIAGONALS[0]],
                     [schedule[14], schedule[15], schedule[8], schedule[9]])
        body += ['movd xmm0, eax', 'movd xmm1, esi', 'movd eax, xmm2', 'movd esi, xmm3']
        body += pair(scalar.DIAGONALS[1:3], schedule[10:14])
        schedule = [schedule[i] for i in scalar.PERM]
    expected = [f'xor {scalar.V[i]}, {scalar.V[i+8]}' for i in range(4)]
    for i in range(4):
        expected += [f'movd eax, xmm{i}', f'xor {scalar.V[4+i]}, eax']
    assert old[feed:feed+12] == expected
    finish = old[feed:feed+4] + ['xor r12d, eax', 'xor r13d, esi',
                               'movd eax, xmm0', 'xor r14d, eax',
                               'movd eax, xmm1', 'xor r15d, eax']
    return setup + body + finish + old[feed+12:]


def main():
    print('// Generated by tools/gen_x86_gpr_resident.py; edit the generator.')
    print('#if defined(__ELF__) && defined(__linux__)\n.section .note.GNU-stack,"",%progbits\n#endif')
    print('.intel_syntax noprefix\n.text\n.p2align 6')
    print('.global blake3_gpr_chunk_root\n.global _blake3_gpr_chunk_root')
    print('blake3_gpr_chunk_root:\n_blake3_gpr_chunk_root:\n        endbr64')
    for ins in kernel():
        print(ins if ins.endswith(':') or ins.startswith('//') else '        ' + ins)


if __name__ == '__main__':
    main()
